"""RT-1407: `scripts/contracts_repin.py` rewrites the whole Connector PIN from one commit.

Frappe-free: the script is loaded by path and run against a throwaway git repository, plus one
read-only check that the real PIN is exactly what the script writes for its own `commit:`.
"""

import importlib.util
import pathlib
import shutil
import subprocess
import tempfile
import unittest

APP_ROOT = pathlib.Path(__file__).resolve().parents[2]
SCRIPT = APP_ROOT / "scripts" / "contracts_repin.py"
MONOREPO = APP_ROOT.parents[1]


def _load():
	spec = importlib.util.spec_from_file_location("contracts_repin", SCRIPT)
	module = importlib.util.module_from_spec(spec)
	spec.loader.exec_module(module)
	return module


repin = _load()


def _git(root, *args):
	return subprocess.run(
		["git", "-C", str(root), *args], capture_output=True, text=True, check=True
	).stdout.strip()


@unittest.skipUnless(shutil.which("git"), "git is required")
class RepinScript(unittest.TestCase):
	def setUp(self):
		self._tmp = tempfile.TemporaryDirectory(prefix="rt1407-")
		self.addCleanup(self._tmp.cleanup)
		self.root = pathlib.Path(self._tmp.name)
		_git(self.root, "init", "-q", "-b", "main")
		self.pin = self.root / repin.PIN_REL

	def commit(self, files):
		for rel, text in files.items():
			path = self.root / repin.SOURCE / rel
			path.parent.mkdir(parents=True, exist_ok=True)
			path.write_text(text, encoding="utf-8")
		_git(self.root, "add", "-A")
		_git(self.root, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", "c")
		return _git(self.root, "rev-parse", "HEAD")

	def write_pin(self, commit, files):
		self.pin.parent.mkdir(parents=True, exist_ok=True)
		self.pin.write_text(repin.format_pin(commit, files), encoding="utf-8")

	def blob(self, commit, rel):
		return _git(self.root, "rev-parse", f"{commit}:{repin.SOURCE}/{rel}")

	def test_every_file_comes_from_the_one_commit(self):
		old = self.commit({"a.yaml": "a: 1\n", "b.yaml": "b: 1\n"})
		new = self.commit({"a.yaml": "a: 2\n"})
		# A mixed PIN: a.yaml at `new`, b.yaml at `old`, `commit:` naming `old`.
		self.write_pin(old, [("a.yaml", self.blob(new, "a.yaml")), ("b.yaml", self.blob(old, "b.yaml"))])
		commit, files = repin.repin(self.root, ref="main")
		self.assertEqual(commit, new)
		self.assertEqual(files, [("a.yaml", self.blob(new, "a.yaml")), ("b.yaml", self.blob(new, "b.yaml"))])
		text = self.pin.read_text(encoding="utf-8")
		self.assertIn(f"commit: {new}\n", text)
		self.assertIn(f"Generated by `{repin.COMMAND}", text)

	def test_ref_pins_an_older_commit(self):
		old = self.commit({"a.yaml": "a: 1\n"})
		self.commit({"a.yaml": "a: 2\n"})
		self.write_pin(old, [("a.yaml", self.blob(old, "a.yaml"))])
		commit, files = repin.repin(self.root, ref=old[:12])
		self.assertEqual((commit, files), (old, [("a.yaml", self.blob(old, "a.yaml"))]))

	def test_second_run_is_identical(self):
		head = self.commit({"a.yaml": "a: 1\n", "b.yaml": "b: 1\n"})
		self.write_pin(head, [("b.yaml", "0" * 40), ("a.yaml", "0" * 40)])
		repin.repin(self.root)
		first = self.pin.read_bytes()
		repin.repin(self.root)
		self.assertEqual(self.pin.read_bytes(), first)

	def test_add_and_remove(self):
		head = self.commit({"a.yaml": "a: 1\n", "b.yaml": "b: 1\n"})
		self.write_pin(head, [("a.yaml", self.blob(head, "a.yaml"))])
		_, files = repin.repin(self.root, add=["b.yaml"], remove=["a.yaml"])
		self.assertEqual(files, [("b.yaml", self.blob(head, "b.yaml"))])

	def test_nothing_is_written_on_error(self):
		head = self.commit({"a.yaml": "a: 1\n"})
		self.write_pin(head, [("a.yaml", self.blob(head, "a.yaml"))])
		before = self.pin.read_bytes()
		cases = (
			{"ref": "no-such-ref"},
			{"add": ["missing.yaml"]},
			{"add": ["../escape.yaml"]},
			{"add": ["a.json"]},
			{"remove": ["not-pinned.yaml"]},
			{"remove": ["a.yaml"]},
		)
		for kwargs in cases:
			with self.subTest(**kwargs), self.assertRaises(repin.RepinError):
				repin.repin(self.root, **kwargs)
			self.assertEqual(self.pin.read_bytes(), before)

	def test_branch_only_commit_is_refused(self):
		"""A squash merge drops branch commits, so a PIN naming one would break after the merge."""
		head = self.commit({"a.yaml": "a: 1\n"})
		self.write_pin(head, [("a.yaml", self.blob(head, "a.yaml"))])
		before = self.pin.read_bytes()
		_git(self.root, "checkout", "-q", "-b", "feature")
		branch = self.commit({"a.yaml": "a: 2\n"})
		with self.assertRaisesRegex(repin.RepinError, "is not on main"):
			repin.repin(self.root, ref=branch)
		self.assertEqual(self.pin.read_bytes(), before)
		self.assertFalse(self.pin.with_name("PIN.tmp").exists())

	def test_origin_main_is_preferred_when_present(self):
		head = self.commit({"a.yaml": "a: 1\n"})
		self.write_pin(head, [("a.yaml", self.blob(head, "a.yaml"))])
		_git(self.root, "update-ref", "refs/remotes/origin/main", head)
		local = self.commit({"a.yaml": "a: 2\n"})  # on local main, not yet on origin/main
		with self.assertRaisesRegex(repin.RepinError, "is not on origin/main"):
			repin.repin(self.root, ref=local)

	def test_cli_reports_failure_with_exit_1(self):
		self.commit({"a.yaml": "a: 1\n"})
		self.assertEqual(repin.main(["--repo", str(self.root), "--ref", "no-such-ref"]), 1)


@unittest.skipUnless(shutil.which("git") and (MONOREPO / ".git").exists(), "needs the monorepo checkout")
class RealPin(unittest.TestCase):
	"""The committed PIN is byte-for-byte what the script writes for its own `commit:`, so it is
	internally consistent (one commit, no hand-edited line) and no one hand-edited it."""

	def test_real_pin_is_generated(self):
		pin = MONOREPO / repin.PIN_REL
		text = pin.read_text(encoding="utf-8")
		[commit] = [line.split()[1] for line in text.splitlines() if line.startswith("commit:")]
		try:
			files = [(p, repin.blob_at(MONOREPO, commit, p)) for p in repin.pinned_paths(text)]
		except repin.RepinError as exc:
			self.skipTest(f"pinned commit not in this clone (fetch full history): {exc}")
		self.assertEqual(text, repin.format_pin(commit, files))


if __name__ == "__main__":
	unittest.main()
