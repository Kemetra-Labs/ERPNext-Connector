"""RT-1407: rewrite the Connector's Backend-Core contract PIN from one commit of this repository.

    python integrations/erpnext-connector/scripts/contracts_repin.py               # every file at `main`
    python integrations/erpnext-connector/scripts/contracts_repin.py --ref <sha|branch|tag>
    python integrations/erpnext-connector/scripts/contracts_repin.py --add erpnext-connector/x.yaml
    python integrations/erpnext-connector/scripts/contracts_repin.py --remove erpnext-connector/x.yaml

The same behaviour as the POS `npm run contracts:repin` (RT-889), without the vendoring: the
Connector keeps no copy of the contracts, only `contracts/backend-core/PIN`. The ref is resolved to
one full commit SHA with local `git`, and every pinned path is read AT THAT COMMIT
(`git rev-parse <commit>:<source>/<path>`), so the PIN can never mix commits. No network and no
GitHub API. The commit must be on `main` (an ancestor of `origin/main`, or of `main` when there is
no `origin/main`): CI reads it from git, and a squash merge drops branch-only commits, so a branch
pin would turn `pins` red after the merge. Fetch first if the clone is shallow. Nothing is written
unless every path resolves to a blob at that commit, and the PIN is replaced atomically. A second
run on the same ref writes the same bytes.

`tools/contracts-check` (`pins`) fails a PIN whose `file:` blob is not the blob of that path at
its `commit:`, so a hand edit of one line does not pass CI. After a repin, run the Connector unit
tests and `tools/contracts-check`, then commit the PIN.
"""

import argparse
import os
import pathlib
import re
import subprocess
import sys

REPO = "Kemetra-Labs/Retail-Tower-Erp"
SOURCE = "services/backend-core/packages/contracts/openapi"
PIN_REL = "integrations/erpnext-connector/contracts/backend-core/PIN"
COMMAND = "python integrations/erpnext-connector/scripts/contracts_repin.py"

_SHA = re.compile(r"^[0-9a-f]{40}$")
_HEADER = (
	"# Backend-Core OpenAPI contracts the ERPNext-Connector consumes (RT-704): the posting feed",
	"# (connector/posting), the bin-view feed (connector/bin_view), the heartbeat (connector/health),",
	"# the ERP-origin stock import feed (connector/stock_import, RT-1287) and the ERP provisioning feed",
	"# (provisioner, RT-1359).",
	"# Checked by tools/contracts-check (`pins`): a Backend-Core change that breaks a pinned file fails,",
	"# and so does a `file:` blob that is not the blob of that path at `commit:` (RT-1407).",
	f"# Generated by `{COMMAND} [--ref <ref>]`; do not hand-edit.",
)


class RepinError(Exception):
	pass


def _git(repo, *args):
	proc = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=False)
	return proc.stdout.strip() if proc.returncode == 0 else None


def check_path(path):
	"""Reject anything that is not a relative `.yaml` path under the contract root."""
	pure = pathlib.PurePosixPath(path)
	if not path or "\\" in path or pure.is_absolute() or any(p in ("", ".", "..") for p in path.split("/")):
		raise RepinError(f"unsafe pinned path {path!r}")
	if not path.endswith(".yaml"):
		raise RepinError(f"pinned path {path!r} is not a .yaml file")
	return path


def pinned_paths(text):
	"""The `file:` paths of an existing PIN, in file order."""
	paths = []
	for line in text.splitlines():
		key, sep, value = line.strip().partition(":")
		if sep and key == "file":
			paths.append(value.split()[0] if value.split() else "")
	return paths


def resolve_commit(repo, ref):
	sha = _git(repo, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}") or ""
	if not _SHA.match(sha):
		raise RepinError(f"ref {ref!r} does not resolve to a commit of this repository (fetch it first)")
	return sha


def check_on_main(repo, commit):
	"""Refuse a commit that is not on main: after a squash merge a branch commit is gone (RT-1407)."""
	for base in ("origin/main", "main"):
		if _git(repo, "rev-parse", "--verify", "--quiet", f"{base}^{{commit}}"):
			if _git(repo, "merge-base", "--is-ancestor", commit, base) is None:
				raise RepinError(f"{commit} is not on {base}; pin a commit that is on main (fetch first)")
			return base
	raise RepinError("neither origin/main nor main exists in this clone; fetch main first")


def blob_at(repo, commit, path):
	spec = f"{commit}:{SOURCE}/{path}"
	sha = _git(repo, "rev-parse", "--verify", "--quiet", spec) or ""
	if not _SHA.match(sha) or _git(repo, "cat-file", "-t", sha) != "blob":
		raise RepinError(f"{path} is not a file at {commit}")
	return sha


def format_pin(commit, files):
	lines = [*_HEADER, f"repo: {REPO}", f"commit: {commit}", f"source: {SOURCE}"]
	lines += [f"file: {path} {blob}" for path, blob in files]
	return "\n".join(lines) + "\n"


def repin(repo, ref="main", add=(), remove=()):
	"""Rewrite the PIN at `ref`. Returns `(commit, [(path, blob)])`; writes nothing on any error."""
	repo = pathlib.Path(repo)
	pin = repo / PIN_REL
	current = pinned_paths(pin.read_text(encoding="utf-8")) if pin.is_file() else []
	unknown = [p for p in remove if p not in current and p not in add]
	if unknown:
		raise RepinError(f"--remove names paths that are not pinned: {', '.join(unknown)}")
	wanted = sorted({check_path(p) for p in [*current, *add]} - set(remove))
	if not wanted:
		raise RepinError("nothing to pin: pass --add <path>")
	commit = resolve_commit(repo, ref)
	check_on_main(repo, commit)
	files = [(path, blob_at(repo, commit, path)) for path in wanted]
	pin.parent.mkdir(parents=True, exist_ok=True)
	tmp = pin.with_name(pin.name + ".tmp")
	tmp.write_text(format_pin(commit, files), encoding="utf-8", newline="\n")
	os.replace(tmp, pin)
	return commit, files


def main(argv=None):
	parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
	parser.add_argument(
		"--ref", default="main", help="commit, branch or tag of this repository (default: main)"
	)
	parser.add_argument(
		"--add",
		action="append",
		default=[],
		metavar="PATH",
		help="also pin this path (relative to the source)",
	)
	parser.add_argument(
		"--remove", action="append", default=[], metavar="PATH", help="stop pinning this path"
	)
	parser.add_argument("--repo", help=argparse.SUPPRESS)
	args = parser.parse_args(argv)
	repo = args.repo or _git(pathlib.Path(__file__).resolve().parent, "rev-parse", "--show-toplevel")
	try:
		if not repo:
			raise RepinError("not inside a git checkout")
		commit, files = repin(repo, args.ref, args.add, args.remove)
	except (RepinError, OSError) as exc:
		sys.stderr.write(f"contracts_repin failed: {exc}\n")
		return 1
	sys.stdout.write(f"Pinned {len(files)} Backend-Core contract(s) at {commit}:\n")
	sys.stdout.writelines(f"  {path} {blob}\n" for path, blob in files)
	return 0


if __name__ == "__main__":
	sys.exit(main())
